#!/usr/bin/env node
// Generates the Swift side of the IPC contract for the SwiftUI Mac shell (ADR-0027 decision 4).
//
// Inputs (the same sources as the TypeScript bindings, so the two shells cannot drift):
//   1. apps/desktop/src/ipc/generated/**/*.ts   ts-rs output for the Rust DTOs
//   2. apps/macos/Sources/OpenFrameCore/Generated/operations.json   operation registry
//      (written by: cargo run -q -p openframe-ffi --features bindgen --bin op-inventory)
// Outputs, in apps/macos/Sources/OpenFrameCore/Generated/:
//   Types.swift       every DTO as a Swift struct, enum or typealias
//   Operations.swift  OperationName constants and one typed CoreInvoking method per operation
//
// Usage:
//   node scripts/gen-swift-types.mjs            write the files
//   node scripts/gen-swift-types.mjs --check    exit 1 and list files that differ (CI drift check)
//
// Mapping choices:
//   number -> Double, bigint -> Int64, T | null and optional keys -> T?, JsonValue/unknown -> JSONValue.
//   Tagged unions become enums with associated values and a hand-generated Codable keyed on the tag.
//   Anything that cannot be mapped faithfully becomes `typealias X = JSONValue` and is listed in the
//   summary at the top of Types.swift. Type names that clash with Swift, Foundation or SwiftUI get the
//   suffix `Dto` everywhere they are referenced.
//   Number encoding: Foundation's JSONEncoder (Swift 6.3) writes Double(1) as `1`, not `1.0`, so Rust
//   integer fields accept it. No custom encoding is needed (checked 2026-10-17). If a future Foundation
//   changes that, add a whole-number encoder here.
//   Output is deterministic: types are sorted by name and nothing depends on time or file order.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tsDir = path.join(root, "apps/desktop/src/ipc/generated");
const outDir = path.join(root, "apps/macos/Sources/OpenFrameCore/Generated");
const opsFile = path.join(outDir, "operations.json");
const HEADER =
  "// Generated by scripts/gen-swift-types.mjs from ts-rs output and the operation registry. Do not edit.\n";

// ---------------------------------------------------------------- tokenizer

function tokenize(src) {
  const toks = [];
  let i = 0;
  let doc = null;
  const n = src.length;
  while (i < n) {
    const ch = src[i];
    if (/\s/.test(ch)) { i++; continue; }
    if (src.startsWith("//", i)) { while (i < n && src[i] !== "\n") i++; continue; }
    if (src.startsWith("/**", i)) {
      const end = src.indexOf("*/", i + 3);
      const body = src.slice(i + 3, end);
      const lines = body.split("\n").map((l) => l.replace(/^\s*\*? ?/, "").trimEnd());
      while (lines.length && lines[0] === "") lines.shift();
      while (lines.length && lines[lines.length - 1] === "") lines.pop();
      doc = (doc ? doc + "\n" : "") + lines.join("\n");
      i = end + 2;
      continue;
    }
    if (src.startsWith("/*", i)) { i = src.indexOf("*/", i + 2) + 2; continue; }
    let tok;
    if (ch === '"') {
      let j = i + 1, s = "";
      while (src[j] !== '"') { if (src[j] === "\\") { s += src[j + 1]; j += 2; } else s += src[j++]; }
      tok = { t: "str", v: s };
      i = j + 1;
    } else if (/[A-Za-z_$]/.test(ch)) {
      let j = i;
      while (j < n && /[A-Za-z0-9_$]/.test(src[j])) j++;
      tok = { t: "id", v: src.slice(i, j) };
      i = j;
    } else if (/[0-9-]/.test(ch)) {
      let j = i + 1;
      while (j < n && /[0-9.]/.test(src[j])) j++;
      tok = { t: "num", v: src.slice(i, j) };
      i = j;
    } else {
      tok = { t: "p", v: ch };
      i++;
    }
    tok.doc = doc;
    doc = null;
    toks.push(tok);
  }
  return toks;
}

// ---------------------------------------------------------------- parser

class Parser {
  constructor(toks) { this.toks = toks; this.p = 0; }
  peek(o = 0) { return this.toks[this.p + o]; }
  next() { return this.toks[this.p++]; }
  isP(v, o = 0) { const t = this.peek(o); return t && t.t === "p" && t.v === v; }
  eat(v) { if (!this.isP(v)) throw new Error(`expected ${v} got ${JSON.stringify(this.peek())}`); return this.next(); }
  parseType() {
    const doc = this.peek()?.doc ?? null;
    if (this.isP("|")) this.next();
    const items = [this.parseInter()];
    while (this.isP("|")) { this.next(); items.push(this.parseInter()); }
    return items.length === 1 ? items[0] : { k: "union", items, doc };
  }
  parseInter() {
    const doc = this.peek()?.doc ?? null;
    const items = [this.parsePrimary()];
    while (this.isP("&")) { this.next(); items.push(this.parsePrimary()); }
    const node = items.length === 1 ? items[0] : { k: "inter", items };
    if (doc && !node.doc) node.doc = doc;
    return node;
  }
  parsePrimary() {
    const t = this.peek();
    const doc = t.doc ?? null;
    let node;
    if (t.t === "str") { this.next(); node = { k: "lit", v: t.v }; }
    else if (t.t === "num") { this.next(); node = { k: "numlit", v: t.v }; }
    else if (t.t === "id") {
      this.next();
      const args = [];
      if (this.isP("<")) {
        this.next();
        args.push(this.parseType());
        while (this.isP(",")) { this.next(); args.push(this.parseType()); }
        this.eat(">");
      }
      node = { k: "ref", name: t.v, args };
    } else if (this.isP("{")) node = this.parseObject();
    else if (this.isP("[")) {
      this.next();
      const items = [];
      if (!this.isP("]")) { items.push(this.parseType()); while (this.isP(",")) { this.next(); items.push(this.parseType()); } }
      this.eat("]");
      node = { k: "tuple", items };
    } else if (this.isP("(")) { this.next(); node = this.parseType(); this.eat(")"); }
    else throw new Error("unexpected token " + JSON.stringify(t));
    while (this.isP("[") && this.isP("]", 1)) { this.next(); this.next(); node = { k: "ref", name: "Array", args: [node] }; }
    if (doc && !node.doc) node.doc = doc;
    return node;
  }
  parseObject() {
    this.eat("{");
    const members = [];
    let index = null;
    while (!this.isP("}")) {
      const first = this.peek();
      const doc = first.doc ?? null;
      if (this.isP("[")) {
        this.next();
        this.next(); // key
        this.next(); // in
        this.parseType();
        this.eat("]");
        if (this.isP("?")) this.next();
        this.eat(":");
        index = this.parseType();
      } else {
        const keyTok = this.next();
        let optional = false;
        if (this.isP("?")) { this.next(); optional = true; }
        this.eat(":");
        const type = this.parseType();
        members.push({ name: keyTok.v, optional, type, doc });
      }
      if (this.isP(",") || this.isP(";")) this.next();
    }
    this.eat("}");
    return { k: "obj", members, index };
  }
}

function parseFile(file) {
  const src = fs.readFileSync(file, "utf8");
  const toks = tokenize(src);
  const p = new Parser(toks);
  const decls = [];
  while (p.p < toks.length) {
    const t = p.peek();
    if (t.t === "id" && t.v === "import") { while (!(p.peek().t === "p" && p.peek().v === ";")) p.next(); p.next(); continue; }
    if (t.t === "id" && t.v === "export") {
      const doc = t.doc ?? null;
      p.next(); p.next(); // export type
      const name = p.next().v;
      p.eat("=");
      const type = p.parseType();
      if (p.isP(";")) p.next();
      decls.push({ name, type, doc, file });
      continue;
    }
    throw new Error(`${file}: unexpected ${JSON.stringify(t)}`);
  }
  return decls;
}

function listTs(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...listTs(full));
    else if (e.name.endsWith(".ts")) out.push(full);
  }
  return out;
}

// ---------------------------------------------------------------- naming

const SWIFT_KEYWORDS = new Set(
  ("associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private " +
    "precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default " +
    "defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self " +
    "Self super throws true try Type").split(" "),
);
const CASE_UNSAFE = new Set(["self", "Self", "init", "Type", "Protocol", "none", "some"]);

// Names that clash with the Swift standard library, Foundation or SwiftUI.
const RESERVED_TYPES = new Set(
  ("Error Data Date URL Result Task Set Range Type Protocol Notification Locale Never Character Index Operation " +
    "Process Bundle Timer Unit Group Selector Array Dictionary String Int Double Bool Optional Codable Decodable " +
    "Encodable Equatable Hashable Sendable Any Self Void Sequence Collection Calendar UUID Decimal Measurement " +
    "Progress Formatter Thread Host Port Pipe Stream Scanner FileManager Page Section Image Color Font View Text " +
    "Button Label List Form Table Menu Scene Toggle Picker Binding State Environment Layout Path Shape Spacer " +
    "Divider Link Stepper Slider TabView Alert Sheet Gesture Transaction Animation Namespace Comparable " +
    "Identifiable Substring Mirror Duration Clock Regex Predicate Expression Cancellable Publisher Subject " +
    "Document Attachment").split(" "),
);

function swiftTypeName(name) {
  return RESERVED_TYPES.has(name) ? name + "Dto" : name;
}

function esc(name) {
  return SWIFT_KEYWORDS.has(name) ? "`" + name + "`" : name;
}

function isIdent(s) {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(s);
}

function lowerCamel(raw) {
  const parts = raw.split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (!parts.length) return raw;
  const lowerHead = (w) => {
    if (/^[A-Z0-9]+$/.test(w)) return w.toLowerCase();
    const m = w.match(/^([A-Z]+)([A-Z][a-z].*)$/);
    if (m) return m[1].toLowerCase() + m[2];
    return w[0].toLowerCase() + w.slice(1);
  };
  const up = (w) => w[0].toUpperCase() + w.slice(1);
  let out = lowerHead(parts[0]) + parts.slice(1).map(up).join("");
  if (/^[0-9]/.test(out)) out = "_" + out;
  return out;
}

function caseName(raw) {
  let n = lowerCamel(raw);
  if (CASE_UNSAFE.has(n)) n += "_";
  return esc(n);
}

/** Unique case names for a list of raw tags. Falls back to the raw spelling, then to numbered names. */
function caseNames(raws) {
  let names = raws.map(caseName);
  if (new Set(names).size !== names.length) {
    names = raws.map((r) => esc(isIdent(r) ? (CASE_UNSAFE.has(r) ? r + "_" : r) : lowerCamel(r)));
  }
  const seen = new Map();
  return names.map((nm) => {
    const c = (seen.get(nm) ?? 0) + 1;
    seen.set(nm, c);
    return c === 1 ? nm : nm + c;
  });
}

function methodName(op) {
  const parts = op.split(/[._]/).filter(Boolean);
  let out = parts[0].toLowerCase();
  for (const p of parts.slice(1)) out += p[0].toUpperCase() + p.slice(1);
  if (/^[0-9]/.test(out)) out = "_" + out;
  return esc(out);
}

function docLines(doc, indent) {
  if (!doc) return "";
  const clean = doc.replace(/ \u2014 /g, ", ").replace(/\u2014/g, "-").replace(/\u2013/g, "-");
  return clean.split("\n").map((l) => (indent + "/// " + l).trimEnd()).join("\n") + "\n";
}

// ---------------------------------------------------------------- classification

const decls = new Map();
for (const f of listTs(tsDir)) {
  for (const d of parseFile(f)) {
    if (d.name === "JsonValue") continue;
    if (decls.has(d.name)) throw new Error("duplicate type " + d.name);
    decls.set(d.name, d);
  }
}

const PRIMS = { string: "String", boolean: "Bool", number: "Double", bigint: "Int64", unknown: "JSONValue", any: "JSONValue", JsonValue: "JSONValue" };

/** Map a TS type to a Swift type string, or throw Unmappable. */
class Unmappable extends Error {}
function mapType(t) {
  if (t.k === "ref") {
    if (PRIMS[t.name]) return PRIMS[t.name];
    if (t.name === "Array" && t.args.length === 1) return "[" + mapType(t.args[0]) + "]";
    if (t.name === "Record" && t.args.length === 2) {
      if (t.args[0].k !== "ref" || t.args[0].name !== "string") throw new Unmappable("Record key is not string");
      return "[String: " + mapType(t.args[1]) + "]";
    }
    if (decls.has(t.name)) return swiftTypeName(t.name);
    throw new Unmappable("unknown type " + t.name);
  }
  if (t.k === "union") {
    const rest = t.items.filter((i) => !(i.k === "ref" && i.name === "null"));
    if (rest.length === 1 && rest.length < t.items.length) {
      const inner = mapType(rest[0]);
      return inner === "JSONValue" ? inner : inner + "?";
    }
    // JsonValue is declared as a union that already contains null; handled by PRIMS.
    throw new Unmappable("inline union");
  }
  if (t.k === "obj" && t.members.length === 0 && t.index) return "[String: " + mapType(t.index) + "]";
  if (t.k === "tuple") throw new Unmappable("tuple");
  throw new Unmappable("inline " + t.k);
}

function isNullable(t) {
  return t.k === "union" && t.items.some((i) => i.k === "ref" && i.name === "null");
}

function isEmptyRecord(t) {
  return t.k === "ref" && t.name === "Record" && t.args.length === 2 && t.args[1].k === "ref" && t.args[1].name === "never";
}

function fieldType(m) {
  let ty = mapType(m.type);
  if (m.optional && !ty.endsWith("?") && ty !== "JSONValue") ty += "?";
  return ty;
}

// Each declaration is classified into: struct | stringEnum | taggedEnum | alias | fallback
const model = new Map(); // name -> {kind, ...}

function classify(d) {
  const t = d.type;
  try {
    if (isEmptyRecord(t)) return { kind: "struct", fields: [] };
    if (t.k === "obj" && !t.index) {
      return { kind: "struct", fields: t.members.map((m) => ({ name: m.name, type: fieldType(m), optional: fieldType(m).endsWith("?"), doc: m.doc })) };
    }
    if (t.k === "obj" && t.index && t.members.length === 0) return { kind: "alias", target: "[String: " + mapType(t.index) + "]" };
    if (t.k === "union" && t.items.every((i) => i.k === "lit")) {
      return { kind: "stringEnum", cases: t.items.map((i) => ({ raw: i.v, doc: i.doc })) };
    }
    if (t.k === "lit") return { kind: "stringEnum", cases: [{ raw: t.v, doc: t.doc }] };
    if (t.k === "union") {
      const tagged = classifyTagged(t);
      if (tagged) return tagged;
      throw new Unmappable("union is not a string enum or an internally tagged union");
    }
    if (t.k === "ref") return { kind: "alias", target: mapType(t) };
    throw new Unmappable("unsupported shape " + t.k);
  } catch (e) {
    if (e instanceof Unmappable) return { kind: "fallback", reason: e.message };
    throw new Error(`${d.name}: ${e.stack}`);
  }
}

function classifyTagged(u) {
  let tagKey = null;
  const variants = [];
  for (const item of u.items) {
    let obj, payload = null;
    if (item.k === "obj") obj = item;
    else if (item.k === "inter" && item.items.length === 2 && item.items[0].k === "obj" && item.items[1].k === "ref") {
      obj = item.items[0];
      payload = item.items[1].name;
    } else return null;
    if (!obj.members.length || obj.members[0].type.k !== "lit" || obj.index) return null;
    const key = obj.members[0].name;
    if (tagKey && key !== tagKey) return null;
    tagKey = key;
    const fields = obj.members.slice(1).map((m) => {
      const ty = fieldType(m);
      return { name: m.name, type: ty, optional: ty.endsWith("?"), doc: m.doc };
    });
    if (payload && fields.length) return null;
    variants.push({ tag: obj.members[0].type.v, fields, payload, doc: item.doc ?? obj.members[0].doc });
  }
  if (new Set(variants.map((v) => v.tag)).size !== variants.length) return null;
  return { kind: "taggedEnum", tagKey, variants };
}

for (const [name, d] of decls) model.set(name, classify(d));

// Payload refs must resolve to structs; otherwise the union cannot flatten faithfully.
for (const [name, m] of model) {
  if (m.kind !== "taggedEnum") continue;
  for (const v of m.variants) {
    if (v.payload && model.get(v.payload)?.kind !== "struct") {
      model.set(name, { kind: "fallback", reason: `flattened payload ${v.payload} is not a plain struct` });
      break;
    }
  }
}
// A struct field that refers to a fallback type is fine (typealias), but an alias of a fallback is too.

// Reserved-name collisions after suffixing.
for (const name of decls.keys()) {
  const sn = swiftTypeName(name);
  if (sn !== name && decls.has(sn)) throw new Error(`name clash: ${name} -> ${sn} already exists`);
}

// ---------------------------------------------------------------- Types.swift

function emitStruct(name, m, doc) {
  const sn = swiftTypeName(name);
  let s = docLines(doc, "") + `public struct ${sn}: Codable, Sendable, Hashable {\n`;
  for (const f of m.fields) {
    if (!isIdent(f.name)) throw new Error(`${name}.${f.name}: not a Swift identifier`);
    s += docLines(f.doc, "    ") + `    public var ${esc(f.name)}: ${f.type}\n`;
  }
  const params = m.fields.map((f) => `${esc(f.name)}: ${f.type}${f.optional ? " = nil" : ""}`);
  if (m.fields.length) s += "\n";
  s += `    public init(${params.join(", ")}) {\n`;
  for (const f of m.fields) s += `        self.${esc(f.name)} = ${esc(f.name)}\n`;
  s += "    }\n}\n";
  return s;
}

function emitStringEnum(name, m, doc) {
  const sn = swiftTypeName(name);
  const names = caseNames(m.cases.map((c) => c.raw));
  let s = docLines(doc, "") + `public enum ${sn}: String, Codable, Sendable, Hashable, CaseIterable {\n`;
  m.cases.forEach((c, i) => {
    const bare = names[i].replace(/`/g, "");
    s += docLines(c.doc, "    ") + `    case ${names[i]}` + (bare === c.raw ? "" : ` = ${JSON.stringify(c.raw)}`) + "\n";
  });
  s += "}\n";
  return s;
}

function emitTagged(name, m, doc) {
  const sn = swiftTypeName(name);
  const names = caseNames(m.variants.map((v) => v.tag));
  const keys = new Set([m.tagKey]);
  for (const v of m.variants) for (const f of v.fields) keys.add(f.name);
  for (const k of keys) if (!isIdent(k)) throw new Error(`${name}: key ${k} is not a Swift identifier`);
  const tagCase = esc(m.tagKey);
  let s = docLines(doc, "") + `public enum ${sn}: Codable, Sendable, Hashable {\n`;
  m.variants.forEach((v, i) => {
    let assoc = "";
    if (v.payload) assoc = `(${swiftTypeName(v.payload)})`;
    else if (v.fields.length) assoc = "(" + v.fields.map((f) => `${esc(f.name)}: ${f.type}`).join(", ") + ")";
    s += docLines(v.doc, "    ") + `    case ${names[i]}${assoc}\n`;
  });
  s += "\n    private enum CodingKeys: String, CodingKey {\n";
  for (const k of [...keys].sort()) s += `        case ${esc(k)}\n`;
  s += "    }\n\n";
  s += "    public init(from decoder: Decoder) throws {\n";
  s += "        let c = try decoder.container(keyedBy: CodingKeys.self)\n";
  s += `        let tag = try c.decode(String.self, forKey: .${esc(m.tagKey)})\n`;
  s += "        switch tag {\n";
  m.variants.forEach((v, i) => {
    s += `        case ${JSON.stringify(v.tag)}:\n`;
    if (v.payload) s += `            self = .${names[i]}(try ${swiftTypeName(v.payload)}(from: decoder))\n`;
    else if (v.fields.length) {
      const args = v.fields.map((f) => {
        const base = f.type.endsWith("?") ? f.type.slice(0, -1) : f.type;
        const fn = f.optional ? "decodeIfPresent" : "decode";
        return `${esc(f.name)}: try c.${fn}(${base}.self, forKey: .${esc(f.name)})`;
      });
      s += `            self = .${names[i]}(${args.join(", ")})\n`;
    } else s += `            self = .${names[i]}\n`;
  });
  s += "        default:\n";
  s += `            throw DecodingError.dataCorrupted(DecodingError.Context(codingPath: decoder.codingPath, debugDescription: "Unknown ${m.tagKey} \\(tag) for ${sn}"))\n`;
  s += "        }\n    }\n\n";
  s += "    public func encode(to encoder: Encoder) throws {\n";
  s += "        var c = encoder.container(keyedBy: CodingKeys.self)\n";
  s += "        switch self {\n";
  m.variants.forEach((v, i) => {
    const tagLine = `try c.encode(${JSON.stringify(v.tag)}, forKey: .${tagCase})`;
    if (v.payload) {
      s += `        case .${names[i]}(let payload):\n            ${tagLine}\n            try payload.encode(to: encoder)\n`;
    } else if (v.fields.length) {
      const binds = v.fields.map((_, j) => `let a${j}`).join(", ");
      s += `        case .${names[i]}(${binds}):\n            ${tagLine}\n`;
      v.fields.forEach((f, j) => {
        s += `            try c.${f.optional ? "encodeIfPresent" : "encode"}(a${j}, forKey: .${esc(f.name)})\n`;
      });
    } else {
      s += `        case .${names[i]}:\n            ${tagLine}\n`;
    }
  });
  s += "        }\n    }\n}\n";
  return s;
}

function buildTypes() {
  const names = [...decls.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const counts = { struct: 0, stringEnum: 0, taggedEnum: 0, alias: 0, fallback: 0 };
  const fallbacks = [];
  let body = "";
  for (const name of names) {
    const m = model.get(name);
    const d = decls.get(name);
    counts[m.kind]++;
    const sn = swiftTypeName(name);
    if (m.kind === "struct") body += emitStruct(name, m, d.doc);
    else if (m.kind === "stringEnum") body += emitStringEnum(name, m, d.doc);
    else if (m.kind === "taggedEnum") body += emitTagged(name, m, d.doc);
    else if (m.kind === "alias") body += docLines(d.doc, "") + `public typealias ${sn} = ${m.target}\n`;
    else {
      fallbacks.push(`${name}: ${m.reason}`);
      body += `// Not mapped faithfully (${m.reason}); the shell treats it as raw JSON.\n` + docLines(d.doc, "") + `public typealias ${sn} = JSONValue\n`;
    }
    body += "\n";
  }
  let head = HEADER + "//\n";
  head += `// Types: ${names.length} (structs ${counts.struct}, string enums ${counts.stringEnum}, tagged enums ${counts.taggedEnum}, aliases ${counts.alias}, JSONValue fallbacks ${counts.fallback}).\n`;
  head += `// Fallbacks to JSONValue (${fallbacks.length}):\n`;
  for (const f of fallbacks) head += `//   ${f}\n`;
  const renamed = names.filter((n) => swiftTypeName(n) !== n);
  head += `// Renamed with the Dto suffix (${renamed.length}): ${renamed.join(", ") || "none"}\n\n`;
  head += "import Foundation\n\n";
  return { text: head + body.replace(/\n+$/, "\n"), counts, fallbacks };
}

// ---------------------------------------------------------------- Operations.swift

function splitTop(s) {
  const out = [];
  let depth = 0, cur = "";
  for (const ch of s) {
    if (ch === "<" || ch === "(") depth++;
    if (ch === ">" || ch === ")") depth--;
    if (ch === "," && depth === 0) { out.push(cur.trim()); cur = ""; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

// Rust names differ from TypeScript names when a DTO carries #[ts(rename = "...")]. The registry holds Rust
// names, so read the renames from the Rust sources (no cargo needed).
function loadRenames() {
  const map = new Map();
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith(".rs")) {
        const src = fs.readFileSync(full, "utf8");
        const re = /#\[ts\([^\]]*?rename = "(\w+)"[^\]]*\][\s\S]{0,400}?pub (?:struct|enum) (\w+)/g;
        for (const m of src.matchAll(re)) {
          if (!map.has(m[2])) map.set(m[2], new Set());
          map.get(m[2]).add(m[1]);
        }
      }
    }
  };
  walk(path.join(root, "crates"));
  return map;
}
const renames = loadRenames();
const ambiguousRust = new Set();
const missingRust = new Set();
const INT = new Set(["u8", "u16", "u32", "i8", "i16", "i32", "usize", "isize"]);
const INT64 = new Set(["i64", "u64", "i128", "u128"]);

function rustToSwift(r) {
  r = r.trim();
  if (r === "()") return "EmptyResult";
  if (r === "String" || r === "str" || r === "&str") return "String";
  if (r === "bool") return "Bool";
  if (INT.has(r)) return "Int";
  if (INT64.has(r)) return "Int64";
  if (r === "f32" || r === "f64") return "Double";
  if (/^(serde_json::)?Value$/.test(r)) return "JSONValue";
  if (r.startsWith("(") && r.endsWith(")")) return "JSONValue";
  const m = r.match(/^([A-Za-z0-9_:]+)<(.*)>$/s);
  if (m) {
    const base = m[1].split("::").pop();
    const args = splitTop(m[2]);
    if (base === "Vec" && args.length === 1) return "[" + rustToSwift(args[0]) + "]";
    if (base === "Option" && args.length === 1) {
      const inner = rustToSwift(args[0]);
      return inner === "JSONValue" ? inner : inner + "?";
    }
    if ((base === "HashMap" || base === "BTreeMap") && args.length === 2) return "[String: " + rustToSwift(args[1]) + "]";
    if (base === "Box" || base === "Arc") return rustToSwift(args[0]);
    missingRust.add(r);
    return "JSONValue";
  }
  const name = r.split("::").pop();
  if (decls.has(name)) return swiftTypeName(name);
  const alt = renames.get(name);
  if (alt && alt.size === 1 && decls.has([...alt][0])) return swiftTypeName([...alt][0]);
  if (alt && alt.size > 1) ambiguousRust.add(name);
  missingRust.add(name);
  return "JSONValue";
}

function emptyStructArg(swiftType) {
  if (swiftType === "EmptyResult") return true;
  for (const [name, m] of model) if (swiftTypeName(name) === swiftType) return m.kind === "struct" && m.fields.length === 0;
  return false;
}

function buildOperations() {
  const ops = JSON.parse(fs.readFileSync(opsFile, "utf8"));
  const methods = new Map();
  let consts = "", exts = "";
  const sorted = [...ops].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const op of sorted) {
    const mn = methodName(op.name);
    if (methods.has(mn)) throw new Error(`method name clash: ${op.name} and ${methods.get(mn)} -> ${mn}`);
    methods.set(mn, op.name);
    const arg = rustToSwift(op.argType);
    const res = rustToSwift(op.resultType);
    consts += `    public static let ${mn} = ${JSON.stringify(op.name)}\n`;
    const dflt = emptyStructArg(arg) ? ` = ${arg}()` : "";
    exts += `    /// ${op.module} ${op.kind}${op.longRunning ? ", long running" : ""}.\n`;
    exts += `    public func ${mn}(_ args: ${arg}${dflt}) async throws -> ${res} { try await call(${JSON.stringify(op.name)}, args) }\n\n`;
  }
  let head = HEADER + "//\n";
  head += `// Operations: ${sorted.length}.\n`;
  const miss = [...missingRust].sort();
  head += `// Rust names resolved through #[ts(rename)] when no TypeScript type has that exact name.\n`;
  head += `// Operation types with no TypeScript declaration, mapped to JSONValue (${miss.length}): ${miss.join(", ") || "none"}\n\n`;
  const text =
    head +
    "import Foundation\n\n" +
    "/// Wire names of every core operation.\npublic enum OperationName {\n" +
    consts +
    "}\n\n" +
    "extension CoreInvoking {\n" +
    exts.replace(/\n+$/, "\n") +
    "}\n";
  return { text, count: sorted.length, missing: miss };
}

